const help = JSON.parse(readFileSync(process.argv[2], 'utf8')).command;
const commands = help.subcommands.filter((c) => c.commandName !== 'help' && c.shouldDisplay !== false);

const hidden = (a) => a.shouldDisplay === false || ['help', 'version'].includes(a.preferredName?.name);
const flagName = (n) => (n.kind === 'short' ? `-${n.name}` : `--${n.name}`);

function usage(path, cmd) {
	const parts = ['proof', ...path];
	if (cmd.subcommands?.length) return parts.concat('<subcommand>').join(' ');
	for (const a of cmd.arguments ?? []) {
		if (hidden(a)) continue;
		let s;
		if (a.kind === 'positional') s = `<${a.valueName}>`;
		else if (a.kind === 'flag') s = flagName(a.preferredName);
		else s = `${flagName(a.preferredName)} <${a.valueName}>`;
		if (a.isRepeating) s += ' ...';
		parts.push(a.isOptional ? `[${s}]` : s);
	}
	return parts.join(' ');
}

const escapeCell = (s) => (s ?? '').replace(/\|/g, '\\|').replace(/\n+/g, ' ');

function argTable(cmd) {
	// --json is on every command: shown in the usage line and the JSON output section, not repeated here.
	const rows = (cmd.arguments ?? []).filter((a) => !hidden(a) && a.preferredName?.name !== 'json');
	if (!rows.length) return '';
	const out = ['| Argument | Description |', '|---|---|'];
	for (const a of rows) {
		let name;
		if (a.kind === 'positional') name = `\`<${a.valueName}>\``;
		else {
			const names = (a.names ?? []).map(flagName).join(', ');
			name = a.kind === 'flag' ? `\`${names}\`` : `\`${names} <${a.valueName}>\``;
		}
		let desc = escapeCell(a.abstract);
		if (a.defaultValue !== undefined && a.defaultValue !== '' && a.kind !== 'flag') desc += ` Default: \`${a.defaultValue}\`.`;
		if (a.isRepeating && a.kind !== 'flag') desc += ' Repeatable.';
		if (!a.isOptional) desc += ' **Required.**';
		out.push(`| ${name} | ${desc.trim()} |`);
	}
	return out.join('\n');
}

function discussion(text) {
	if (!text) return '';
	const lines = text.split('\n');
	// Indented lines are examples: keep them in a code block, the rest as prose.
	const out = [];
	let code = [];
	const flush = () => { if (code.length) { out.push('```text', ...code, '```'); code = []; } };
	for (const l of lines) {
		if (/^\s{2,}\S/.test(l)) code.push(l.replace(/^\s{2}/, ''));
		else { flush(); out.push(l); }
	}
	flush();
	return out.join('\n').trim();
}

function anchor(type) { return type.toLowerCase(); }

function outputsFor(pathKey) {
	const top = pathKey.split(' ')[0];
	const list = OUTPUTS[pathKey] ?? OUTPUTS[top];
	if (!list) return '';
	const items = list.map(([type, when]) => `- [\`${type}\`](../../json-output/#${anchor(type)})${when ? `: ${when}` : ''}`);
	return ['**JSON output** (`--json`):', '', ...items].join('\n');
}

function section(path, cmd, level) {
	const h = '#'.repeat(level);
	const out = [];
	if (level > 2 || path.length > 1) out.push(`${h} proof ${path.join(' ')}`, '');
	if (cmd.abstract) out.push(cmd.abstract, '');
	out.push('```sh', usage(path, cmd), '```', '');
	const d = discussion(cmd.discussion);
	if (d) out.push(d, '');
	const t = argTable(cmd);
	if (t) out.push(t, '');
	if (!cmd.subcommands?.length) {
		const o = outputsFor(path.join(' '));
		if (o) out.push(o, '');
	}
	return out.join('\n');
}

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

commands.forEach((cmd, i) => {
	const name = cmd.commandName;
	const subs = (cmd.subcommands ?? []).filter((s) => s.shouldDisplay !== false && s.commandName !== 'help');
	const body = [
		'---',
		`title: proof ${name}`,
		`description: ${JSON.stringify(cmd.abstract ?? '')}`,
		'sidebar:',
		`  order: ${i + 1}`,
		'---',
		'',
		GENERATED,
		'',
		section([name], { ...cmd, subcommands: subs }, 2),
	];
	if (subs.length) {
		body.push('**Subcommands:** ' + subs.map((s) => `[\`${s.commandName}\`](#proof-${name}-${s.commandName})`).join(' · '), '');
		for (const s of subs) body.push(section([name, s.commandName], s, 2));
	}
	writeFileSync(join(outDir, `${name}.md`), body.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n');
});

// JSON output page
const json = [
	'---',
	'title: JSON output',
	'description: What every command prints with --json, field by field, with examples.',
	'---',
	'',
	GENERATED,
	'',
	'Add `--json` to any command to get its result as one JSON object on stdout. Progress messages still go',
	'to stderr, so stdout is always valid JSON. The exit code is the same as without `--json`.',
	'',
	'Optional fields (marked `?`) are left out when they have no value. Paths in examples are shortened;',
	'real output has absolute paths.',
	'',
	'| Type | Printed by |',
	'|---|---|',
];
for (const type of Object.keys(TYPES)) {
	const by = Object.entries(OUTPUTS).filter(([, l]) => l.some(([t]) => t === type))
		.map(([cmd, l]) => {
			const when = l.find(([t]) => t === type)[1];
			const link = `[\`proof ${cmd}\`](../commands/${cmd.split(' ')[0]}/)`;
			return when && when.startsWith('with') ? `${link} ${when}` : link;
		});
	json.push(`| [\`${type}\`](#${anchor(type)}) | ${by.join(', ')} |`);
}
json.push('');
const fieldTable = (rows) => ['| Field | Type | Description |', '|---|---|---|', ...rows.map(([f, t, d]) => `| \`${f}\` | \`${t}\` | ${escapeCell(d)} |`)].join('\n');
const pretty = (name) => JSON.stringify(JSON.parse(readFileSync(join(examplesDir, `${name}.json`), 'utf8')), null, 2);
const available = new Set(readdirSync(examplesDir).map((f) => f.replace(/\.json$/, '')));

for (const [type, t] of Object.entries(TYPES)) {
	json.push(`## ${type}`, '', t.summary, '', fieldTable(t.fields), '');
	for (const [n, rows] of Object.entries(t.nested ?? {})) json.push(`**${n}**`, '', fieldTable(rows), '');
	for (const ex of [t.example, ...(t.extraExamples ?? [])].filter(Boolean)) {
		if (!available.has(ex)) throw new Error(`missing example ${ex}.json: run make docs-reference`);
		json.push('```json', pretty(ex), '```', '');
	}
}
writeFileSync(join(docs, 'src/content/docs/reference/json-output.md'), json.join('\n').trimEnd() + '\n');

console.log(`wrote ${commands.length} command pages and json-output.md`);
